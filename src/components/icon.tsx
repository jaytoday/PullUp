export type IconProps = Omit<SVGProps<SVGSVGElement>, "ref"> & {
  /** `i-lucide-<name>`, `i-simple-icons-<name>`, or a bare lucide name. */
  name: string;
};

export function Icon({ name, className, ...props }: IconProps) {
  const classes = cn("inline-block size-4 shrink-0", className);

  if (name.startsWith("i-simple-icons-")) {
    const path = BRANDS[name.slice("i-simple-icons-".length)];
    if (path) {
      return (
        <svg viewBox="0 0 24 24" fill="currentColor" aria-hidden="true" className={classes} {...props}>
          <path d={path} />
        </svg>
      );
    }
  }

  const key = name.startsWith("i-lucide-") ? name.slice("i-lucide-".length) : name;
  const Lucide = LUCIDE[key] ?? LUCIDE.circle!;
  return <Lucide aria-hidden="true" className={classes} {...props} />;
}
